#!/bin/sh
# Restore into a newly created disposable database, never into the live database.
set -eu
umask 077
root="$HOME/auratrade"
mkdir -p "$root/health"
exec 9>"$root/health/.restore.lock"
flock -n 9 || exit 0
health="$root/bin/health-status.py"
check_db="auratrade_restore_check_$(date -u +%Y%m%d%H%M%S)_$$"
created=false
case "$check_db" in auratrade_restore_check_[0-9]*_[0-9]*) ;; *) exit 2 ;; esac
cleanup() {
    code=$?
    trap - EXIT
    if [ "$created" = true ]; then
        # The flag is set only after this invocation successfully creates it.
        if ! docker exec auratrade-db-1 dropdb -U auratrade "$check_db"; then code=1; fi
    fi
    if [ "$code" -eq 0 ]; then
        python3 "$health" restore success || code=1
    else
        python3 "$health" restore failed || true
    fi
    exit "$code"
}
trap cleanup EXIT
python3 "$health" restore running
# Backup names have no spaces and are generated by backup.sh. Choose the newest
# finalized dump only; a partial/failed dump must never qualify as restore proof.
dump=$(find "$root/backups" -maxdepth 1 -type f -name 'auratrade-*.dump' -printf '%f\n' | sort -r | head -n 1)
[ -n "$dump" ] || { echo "No finalized backup is available." >&2; exit 1; }
docker exec auratrade-db-1 createdb -U auratrade "$check_db"
created=true
docker exec -i auratrade-db-1 pg_restore -U auratrade --no-owner --exit-on-error -d "$check_db" < "$root/backups/$dump"
# Validate schema and queryability. Do not print restored user data or counts.
docker exec auratrade-db-1 psql -U auratrade -d "$check_db" -v ON_ERROR_STOP=1 -Atc 'SELECT count(*) FROM "_prisma_migrations"; SELECT count(*) FROM "RoundTripTrade"; SELECT count(*) FROM "User";' >/dev/null
echo "Backup restored and queried successfully in a disposable database."
